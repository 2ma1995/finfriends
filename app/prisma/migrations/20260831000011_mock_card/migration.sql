-- 🔴 **이것은 카드가 아니다.** 실제 발급은 제휴사가 한다(`PTN-001` · §6.1 진입점 9번
--    `requestCard`)이고 착수 조건인 **D1(수수료율·SLA·업종 코드)** 과
