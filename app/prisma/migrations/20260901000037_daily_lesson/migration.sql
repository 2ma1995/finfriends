-- 읽을거리도 하루에 하나 — 어긋남 대장 D47
--
-- 🔴 **퀴즈만 하루 하나였다.** 「매일 조금씩」이 이 제품의 리듬인데
--    읽을거리는 목록이 통째로 열려 있어서 **하루에 다 읽을 수 있었다.**
--    다 읽고 나면 그 영역은 그날로 끝이고, 다음 날 열 이유가 없어진다.
--
-- 🔴 **언제 읽었는지를 아무 데도 안 남기고 있었다.** `learning_progress` 는
--    읽은 편의 **목록**만 갖고 `updated_at` 하나뿐이라, 퀴즈 정답으로도 갱신된다 —
--    「오늘 새 편을 읽었나」를 물을 수가 없었다.
--
-- 🔴 **KST 날짜 문자열로 담는다.** `timestamptz` 로 두면 「오늘」을 물을 때마다
--    시간대를 되돌려야 하고, 서버가 어디서 도는지에 따라 경계가 흔들린다.
--    `kstDay()` 가 주는 값을 그대로 넣는다.

ALTER TABLE "activity"."learning_progress"
  ADD COLUMN "last_read_day" TEXT;
