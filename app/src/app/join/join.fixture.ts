/** 이름이 들어가는 문장이 있어 함수로 둔다 — 화면에서 문자열을 치환하지 않는다 */
export function whatHappens(childName: string): readonly string[] {
  return [
    `이 기기를 열면 바로 ${childName}의 화면이 나옵니다.`,
    `${childName}은 아이디도 비밀번호도 입력하지 않습니다.`,
    "부모가 로그아웃해도 이 기기는 계속 열립니다 — 옆에 없어도 아이가 씁니다.",
    "승인·소비 같은 부모 화면은 이 기기에서 열리지 않습니다.",
    "등록하면 이 기기에서 부모 로그인은 끝납니다 — 부모 화면은 부모 기기에서 보세요.",
  ];
}

