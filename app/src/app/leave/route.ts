import { NextResponse, type NextRequest } from "next/server";
import { forgetSession } from "@/lib/session/forget";

/**
 * 죽은 세션을 털고 처음 화면으로 — 어긋남 대장 D72 · 사용자 요청.
 *
 * 🔴 **쿠키는 남았는데 세션은 죽은 상태**가 있다. 서버에서 세션을 닫았거나,
 *    보호자 세션 14일이 지났거나, 기기 연결이 풀렸을 때다.
 *    그때 `/` 를 열면 미들웨어는 **쿠키가 있으니** 랜딩으로 안 보내고,
 *    `/` 의 서버 코드는 **세션이 죽었으니** 로그인으로 보냈다.
 *
 *    그래서 로그인 화면에서 「처음으로」를 눌러도 **다시 로그인으로 돌아왔다.**
 *    나가는 길이 있는데 그 길이 제자리로 돌아오는 원이었다.
 *
 * 🔴 **고치는 자리는 여기다.** 미들웨어는 쿠키만 보므로 살았는지 죽었는지 모르고,
 *    화면(RSC)은 쿠키를 지우지 못한다. **죽은 것을 확인한 쪽이 여기로 보내고,
 *    여기가 지운다.**
 *
 * 🔴 되돌아오는 곳은 `/` 다. 쿠키가 없어졌으니 미들웨어가 랜딩으로 rewrite 한다 —
 *    「랜딩으로 보낸다」고 여기서 정하지 않는다. 가르는 규칙은 한 곳에만 둔다.
 *
 * 🔴 **원이 되지 않는다.** 쿠키가 지워지므로 다음 `/` 는 랜딩에서 멈춘다.
 *    실제로 밟아 봤다 — `/` → 여기 → `/`, 두 번에 랜딩. 남은 세션 쿠키 0건.
 *
 * 🔴 **GET 이라 남이 링크로 걸어 로그아웃시킬 수 있다.** 그래도 GET 으로 둔다 —
 *    잃는 것은 세션뿐이고(데이터는 그대로), 이 길은 **이미 갇힌 사람이 나오는 문**이라
 *    폼 제출을 거쳐야 하면 정작 필요한 순간에 못 쓴다. `/child/left` 도 같은 성질이다.
 */
export async function GET(req: NextRequest) {
  const url = req.nextUrl.clone();
  url.pathname = "/";
  url.search = "";
  return forgetSession(NextResponse.redirect(url));
}
