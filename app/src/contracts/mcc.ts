/**
 * 🔴 **일부러 미분류로 보내는 코드.** 포괄 코드라 무엇을 샀는지 알 수 없다 —
 *    틀린 봉투에서 빼면 아이가 「왜 여기서 빠졌지」를 묻는데 답할 수 없다.
 */
export const AMBIGUOUS = new Set([
  "5300", // 창고형 매장
  "5310", // 할인점
  "5311", // 백화점
  "5331", // 잡화점 — 다이소류가 여기로 들어오는 일이 많다
  "5399", // 기타 종합 소매
  "5999", // 기타 소매
  "5964", // 통신판매
  "5967", // 온라인 결제 대행
]);

/** MCC → 우리 업종. 모르면 null 이고, null 이면 **미분류 봉투**로 간다 */
export function categoryFromMcc(mcc: string | null | undefined): CategoryCode | null {
  if (!mcc) return null;
  const code = mcc.trim();
  if (AMBIGUOUS.has(code)) return null;
  return MCC_MAP[code] ?? null;
}

