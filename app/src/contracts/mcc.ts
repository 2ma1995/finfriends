/**
 * 가맹점 업종 코드(MCC) → 우리 업종 — `FR-021` · `DAT-004` 의 자리.
 *
 * MCC 는 **ISO 18245** 네 자리 코드다. 카드 결제 승인 때 매입사가 가맹점에 붙여 보낸다.
 *
 * 🔴 **이 표는 초안이다.** 코드값은 표준이라 틀리지 않지만, **어느 가게에 어느 코드가
 *    붙는지는 매입사가 정한다.** 같은 문구점이 매입사에 따라 `5943`(문구)일 수도
 *    `5399`(잡화)일 수도 있다. 그래서 `NFR-024`(매칭 정확도 ≥90%)를 이 표만으로는
 *    보증할 수 없고, 문서도 **「제휴 후 검증」**으로 두었다.
 *
 * 🔴 **한국은 포괄 코드가 많다.** 동네 가게가 `5399`·`5999` 로 뭉뚱그려 들어오는 일이 흔하다.
 *    그런 코드는 **일부러 미분류로 보낸다** — 틀린 봉투에서 빼는 것보다 「모르겠어요」가 낫다.
 *
 * 🔴 **틀렸을 때 고칠 길이 있어야 한다.** 표를 아무리 다듬어도 오분류는 남는다.
 *    보호자가 고친 것이 다음부터 반영되는 길(`merchant overrides`)이 이 표보다 중요하다.
 */

